<?php

namespace App\Models;

use App\Models\Concerns\HasUuid;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

class Notification extends Model
{
    use HasFactory, HasUuid;

    protected $table = 'notifications';

    public const TYPE_BUDGET_WARNING = 'budget_warning';
    public const TYPE_BUDGET_EXCEEDED = 'budget_exceeded';
    public const TYPE_PUBLISH_SUCCESS = 'publish_success';
    public const TYPE_PUBLISH_FAILED = 'publish_failed';
    public const TYPE_TOKEN_EXPIRING = 'token_expiring';

    protected $fillable = [
        'user_id',
        'type',
        'title',
        'message',
        'data',
        'read_at',
    ];

    protected $casts = [
        'data' => 'array',
        'read_at' => 'datetime',
    ];

    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function isRead(): bool
    {
        return $this->read_at !== null;
    }

    public function markAsRead(): void
    {
        $this->update(['read_at' => now()]);
    }
}
